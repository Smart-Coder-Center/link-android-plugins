#!/usr/bin/env python3
import base64
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

root = Path(sys.argv[1]).resolve()
output = Path(sys.argv[2]).resolve()
public_key = Path("keys/native-runtime-ed25519-public.pem").resolve()
private_key = os.environ.get("LINK_PLUGIN_RUNTIME_SIGNING_PRIVATE_KEY", "").strip()
if not private_key:
    raise SystemExit("LINK_PLUGIN_RUNTIME_SIGNING_PRIVATE_KEY is not configured; refusing unsigned runtime package")
if not public_key.is_file():
    raise SystemExit("Pinned Ed25519 public key is missing")

metadata = json.loads((root / "plugin.json").read_text(encoding="utf-8"))
generated_path = root / ".link-runtime-generated.json"
if not generated_path.is_file():
    raise SystemExit("Runtime metadata was not generated by the ML Kit builder")
runtime = dict(metadata.get("runtime") or {})
runtime.update(json.loads(generated_path.read_text(encoding="utf-8")))
if metadata.get("id") != "ml-translate" or metadata.get("package_type") != "native_runtime":
    raise SystemExit("Unexpected plugin identity or package type")
if runtime.get("abis") != ["arm64-v8a"] or not runtime.get("load_order"):
    raise SystemExit("ML Kit runtime ABI or native load order is invalid")
if runtime.get("entry_class") != "eu.siacs.link.plugins.translate.MlKitTranslatePlugin":
    raise SystemExit("Unexpected ML Kit runtime entry class")
if runtime.get("code_api_version") != 1:
    raise SystemExit("Unsupported runtime code API version")

payload = []
for path in sorted(root.rglob("*")):
    if not path.is_file() or path in {root / "plugin.json", generated_path}:
        continue
    relative = path.relative_to(root)
    if "provenance" in relative.parts:
        continue
    if relative.parts[0] not in {"code", "lib", "NOTICE"}:
        raise SystemExit(f"Unreviewed runtime payload path: {relative}")
    if path.is_symlink():
        raise SystemExit(f"Symlink is not allowed: {relative}")
    payload.append((relative.as_posix(), path))
if not payload:
    raise SystemExit("Runtime package payload is empty")

dex_paths = sorted(name for name, _ in payload if name.startswith("code/") and name.endswith(".dex"))
so_paths = sorted(name for name, _ in payload if name.startswith("lib/") and name.endswith(".so"))
if dex_paths != sorted(runtime.get("code_files", [])):
    raise SystemExit("runtime.code_files does not match the DEX payload")
if so_paths != sorted(runtime.get("load_order", [])):
    raise SystemExit("runtime.load_order does not match the JNI payload")
if not dex_paths or not so_paths or "NOTICE" not in {name for name, _ in payload}:
    raise SystemExit("DEX, JNI libraries, and NOTICE are all required")

signed_manifest = dict(metadata)
signed_manifest.pop("source", None)
signed_manifest.pop("archive", None)
signed_manifest["runtime"] = runtime
signed_manifest["files"] = [
    {"path": name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    for name, path in payload
]
manifest_bytes = (json.dumps(signed_manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")

output.parent.mkdir(parents=True, exist_ok=True)
with tempfile.TemporaryDirectory(prefix="link-mlkit-sign-") as temp:
    temp = Path(temp)
    private_path = temp / "private.pem"
    derived_public = temp / "derived-public.pem"
    manifest_path = temp / "plugin.json"
    signature_path = temp / "plugin.json.sig"
    private_path.write_text(private_key + "\n", encoding="utf-8")
    manifest_path.write_bytes(manifest_bytes)
    subprocess.run(["openssl", "pkey", "-in", str(private_path), "-pubout", "-out", str(derived_public)],
                   check=True, capture_output=True)
    if derived_public.read_bytes().strip() != public_key.read_bytes().strip():
        raise SystemExit("Signing private key does not match the pinned Ed25519 public key")
    subprocess.run(["openssl", "pkeyutl", "-sign", "-rawin", "-inkey", str(private_path),
                    "-in", str(manifest_path), "-out", str(signature_path)], check=True, capture_output=True)
    subprocess.run(["openssl", "pkeyutl", "-verify", "-pubin", "-inkey", str(public_key),
                    "-rawin", "-in", str(manifest_path), "-sigfile", str(signature_path)],
                   check=True, capture_output=True)
    signature_raw = signature_path.read_bytes()
    signature_b64 = base64.b64encode(signature_raw)

with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
    def add_bytes(name, data):
        info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.create_system = 3
        info.external_attr = 0o100644 << 16
        archive.writestr(info, data, compress_type=zipfile.ZIP_DEFLATED, compresslevel=6)
    add_bytes("plugin.json", manifest_bytes)
    add_bytes("plugin.json.sig", signature_b64)
    for name, path in payload:
        info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.create_system = 3
        info.external_attr = 0o100644 << 16
        with archive.open(info, "w", force_zip64=True) as target, path.open("rb") as source:
            while True:
                chunk = source.read(1024 * 1024)
                if not chunk:
                    break
                target.write(chunk)

with zipfile.ZipFile(output) as archive:
    if archive.testzip() is not None:
        raise SystemExit("Generated plugin ZIP failed CRC validation")
    names = set(archive.namelist())
    expected = {"plugin.json", "plugin.json.sig"} | {name for name, _ in payload}
    if names != expected:
        raise SystemExit("Generated plugin ZIP contains missing or unexpected entries")
    if archive.read("plugin.json") != manifest_bytes:
        raise SystemExit("ZIP manifest differs from the signed manifest bytes")
    if base64.b64decode(archive.read("plugin.json.sig")) != signature_raw:
        raise SystemExit("ZIP signature differs from the verified Ed25519 signature")

digest = hashlib.sha256(output.read_bytes()).hexdigest()
print(json.dumps({
    "plugin_id": metadata["id"],
    "version": metadata["version"],
    "archive": str(output),
    "archive_size_bytes": output.stat().st_size,
    "archive_sha256": digest,
    "signed_manifest": True,
    "signature_verified": True,
    "payload_files": len(payload),
    "payload_bytes": sum(path.stat().st_size for _, path in payload)
}, indent=2))
